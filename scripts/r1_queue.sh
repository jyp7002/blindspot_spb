#!/usr/bin/env bash
# R1 queue: run one or more passes back to back on this GPU, one unit per process.
#
#   bash scripts/r1_queue.sh "passA:configs/r1/e4.yaml:C-rand" \
#                            "e7b_pub:configs/r1/e7b.yaml:pub:run_r1_dpo.py" \
#                            "passB:configs/r1/e5.yaml" \
#                            "passC:configs/r1/e4.yaml"
#
# Each argument is  <tag>:<config>[:<comma-separated arms>[:<runner>]].
# Arms default to the config's; the runner defaults to run_r1.py. A pass walks
# the config's units in order; the runners skip whatever is already on disk, so
# re-running the same command after a crash or a deliberate stop resumes.
#
# Uses the same pidfile lock as scripts/submit_local.sh (logs/.queue.pid): two
# queues on one card would OOM, and waiting on a pgrep string match deadlocks.
#
# Do not edit this file while a queue is running: bash reads a script as it
# goes. Stop the queue first (kill the children of the pid in logs/.queue.pid,
# then the pid), replace the file, and start again.
set -uo pipefail
cd "$(dirname "$0")/.."

PY="${PY:-python3}"
QUEUE_PID_FILE="logs/.queue.pid"
mkdir -p logs/r1
if [ -f "$QUEUE_PID_FILE" ] && kill -0 "$(cat "$QUEUE_PID_FILE" 2>/dev/null)" 2>/dev/null; then
  echo "another queue is live (pid $(cat "$QUEUE_PID_FILE")); refusing to start a second on one GPU"
  exit 1
fi
echo $$ > "$QUEUE_PID_FILE"
trap 'rm -f "$QUEUE_PID_FILE"' EXIT
rm -f logs/r1/CHAIN_DONE

fail=0
for spec in "$@"; do
  IFS=':' read -r tag cfg arms runner <<< "$spec"
  runner="${runner:-run_r1.py}"
  armopt=()
  [ -n "${arms:-}" ] && armopt=(--arms "$arms")
  logdir="logs/r1/$tag"
  mkdir -p "$logdir"
  rm -f "$logdir/PASS_DONE"
  n=$($PY "$runner" --config "$cfg" --count) || { echo "[$tag] bad config $cfg"; fail=1; continue; }
  echo "[$(date -u +%FT%TZ)] pass $tag: $runner $cfg arms=${arms:-<config>} units=$n" | tee -a logs/r1/queue.log
  for ((i=0; i<n; i++)); do
    $PY "$runner" --config "$cfg" --unit "$i" "${armopt[@]}" >> "$logdir/unit_${i}.log" 2>&1
    rc=$?
    if [ $rc -ne 0 ]; then
      echo "[$(date -u +%FT%TZ)] [$tag] unit $i FAILED rc=$rc (see $logdir/unit_${i}.log)" | tee -a logs/r1/queue.log
      fail=1          # keep going: one bad unit must not strand the pass
    fi
  done
  $PY "$runner" --config "$cfg" --progress "${armopt[@]}" | tee -a logs/r1/queue.log
  date -u +%FT%TZ > "$logdir/PASS_DONE"
  echo "[$(date -u +%FT%TZ)] pass $tag done" | tee -a logs/r1/queue.log
done
echo "fail=$fail $(date -u +%FT%TZ)" > logs/r1/CHAIN_DONE
exit $fail
